<h2 id="erros">Erros comuns (e como evitar)</h2>
<ul>
  <li><strong>Calcular tudo no fim do mês.</strong> Um atendimento esquecido ou cancelado vira diferença difícil de achar. Registre o repasse a cada atendimento realizado.</li>
