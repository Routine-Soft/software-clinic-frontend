<blockquote><strong>Formato SOAP.</strong> S: relata semana mais tranquila, dormindo melhor. O: humor estável, discurso organizado, mais contato visual que nas sessões anteriores. A: boa adesão às estratégias; redução dos sintomas relatados. P: manter frequência semanal; iniciar trabalho sobre a relação com a família na próxima sessão.</blockquote>

